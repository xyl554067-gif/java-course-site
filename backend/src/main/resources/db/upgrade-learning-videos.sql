CREATE TABLE IF NOT EXISTS learning_video (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bvid VARCHAR(12) NOT NULL UNIQUE,
    source_url VARCHAR(255) NOT NULL,
    title VARCHAR(160) NOT NULL,
    uploader VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS lesson_video (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lesson(id) ON DELETE CASCADE,
    video_id BIGINT NOT NULL REFERENCES learning_video(id) ON DELETE CASCADE,
    part_number INTEGER NOT NULL DEFAULT 1 CHECK (part_number >= 1),
    start_seconds INTEGER NOT NULL DEFAULT 0 CHECK (start_seconds >= 0),
    label VARCHAR(160) NOT NULL,
    recommendation VARCHAR(512),
    sort_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (lesson_id, video_id, part_number, start_seconds)
);
