-- Run once against an existing database. Safe to re-run on KingbaseES/PostgreSQL.
CREATE TABLE IF NOT EXISTS generated_course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    title VARCHAR(160) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    source_name VARCHAR(255),
    source_url VARCHAR(1000),
    source_text TEXT,
    course_json TEXT NOT NULL,
    share_token VARCHAR(64),
    share_revoked SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_generated_owner ON generated_course(owner_id,updated_at);
CREATE UNIQUE INDEX IF NOT EXISTS uk_generated_share ON generated_course(share_token);

CREATE TABLE IF NOT EXISTS learning_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    lesson_id BIGINT NOT NULL REFERENCES lesson(id) ON DELETE CASCADE,
    session_key VARCHAR(64) NOT NULL,
    activity_date DATE NOT NULL DEFAULT CURRENT_DATE,
    session_seconds INTEGER NOT NULL DEFAULT 0,
    total_seconds INTEGER NOT NULL DEFAULT 0,
    completed SMALLINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_activity_session_day ON learning_activity(user_id,lesson_id,session_key,activity_date);
CREATE INDEX IF NOT EXISTS idx_activity_user_day ON learning_activity(user_id,activity_date);

CREATE TABLE IF NOT EXISTS learning_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    lesson_id BIGINT NOT NULL REFERENCES lesson(id) ON DELETE CASCADE,
    session_key VARCHAR(64) NOT NULL,
    last_seconds INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_learning_session_key ON learning_session(user_id,lesson_id,session_key);

CREATE TABLE IF NOT EXISTS user_ai_config (
    user_id BIGINT PRIMARY KEY REFERENCES app_user(id) ON DELETE CASCADE,
    base_url VARCHAR(1000) NOT NULL,
    model VARCHAR(160) NOT NULL,
    encrypted_key VARCHAR(4096) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

