-- ============================================================================
-- Java 课程介绍网站 — KingbaseES V8 数据库结构
-- 目标版本: KingbaseES V8R6 (dbmode=oracle, UTF8)
-- 兼容说明（2026-10-22 实测校正）:
--   * 本实例已实测支持：tsvector + GIN 全文检索、json/jsonb、数组与数组切片、
--     物化视图、窗口函数、ON CONFLICT。本schema 目前仍走应用层分词，
--     是为了在没有 zhparser 的前提下保证中文召回可控。
--   * 实测【不支持】：vector 扩展（share/extension/vector 不存在）——
--     如需语义检索，embedding 请存float4[] 或 jsonb，在应用层算余弦相似度。
--   * zhparser 需 superuser 权限才能安装，故不依赖数据库分词。
--   * 字段名避开保留字(user, level, order, session, comment, size, type)
--   * 自增主键用 IDENTITY，避免依赖序列
--   * 时间统一 timestamptz
-- ============================================================================

-- ---------- 用户与登录 ----------
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(128) NOT NULL,
    salt          VARCHAR(32)  NOT NULL,
    nickname      VARCHAR(64),
    email         VARCHAR(128),
    avatar        VARCHAR(255),
    role          VARCHAR(20)  NOT NULL DEFAULT 'student',
    status        VARCHAR(20)  NOT NULL DEFAULT 'active',
    last_login_at TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_app_user_username ON app_user (username);
CREATE INDEX idx_app_user_email ON app_user (email);

CREATE TABLE user_session (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token        VARCHAR(256) NOT NULL,
    user_id      BIGINT      NOT NULL,
    user_agent   VARCHAR(255),
    client_ip    VARCHAR(64),
    expires_at   TIMESTAMPTZ NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_user_session_token ON user_session (token);
CREATE INDEX idx_user_session_user ON user_session (user_id);
CREATE INDEX idx_user_session_expires ON user_session (expires_at);

-- ---------- 课程内容结构 ----------
CREATE TABLE course (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug         VARCHAR(64)  NOT NULL,
    title        VARCHAR(160) NOT NULL,
    subtitle     VARCHAR(255),
    description  TEXT,
    cover_image  VARCHAR(255),
    instructor   VARCHAR(64),
    version      VARCHAR(32),
    difficulty   VARCHAR(20)  NOT NULL DEFAULT 'BEGINNER',
    status       VARCHAR(20)  NOT NULL DEFAULT 'PUBLISHED',
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    total_lessons INTEGER     NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_course_slug ON course (slug);
CREATE INDEX idx_course_status ON course (status, sort_order);

CREATE TABLE course_module (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id    BIGINT       NOT NULL,
    title        VARCHAR(160) NOT NULL,
    summary      VARCHAR(512),
    icon         VARCHAR(64),
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    lesson_count INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_module_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE
);
CREATE INDEX idx_module_course ON course_module (course_id, sort_order);

CREATE TABLE lesson (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id    BIGINT       NOT NULL,
    title        VARCHAR(160) NOT NULL,
    slug         VARCHAR(160) NOT NULL,
    summary      VARCHAR(512),
    content      CLOB,
    content_html CLOB,
    duration_min INTEGER      NOT NULL DEFAULT 0,
    difficulty   VARCHAR(20)  NOT NULL DEFAULT 'BEGINNER',
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    is_preview   SMALLINT     NOT NULL DEFAULT 0,
    view_count   INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lesson_module FOREIGN KEY (module_id) REFERENCES course_module (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uk_lesson_slug ON lesson (slug);
CREATE INDEX idx_lesson_module ON lesson (module_id, sort_order);
CREATE INDEX idx_lesson_difficulty ON lesson (difficulty);

CREATE TABLE code_snippet (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id    BIGINT       NOT NULL,
    language     VARCHAR(32)  NOT NULL DEFAULT 'java',
    title        VARCHAR(160),
    code_text    CLOB         NOT NULL,
    explanation  CLOB,
    -- 是否为「可完整编译运行的示例」：只有完整程序的示例才置 1，
    -- 片段代码（缺 class / main）置 0，前端不给运行按钮，避免误导学生
    runnable     BOOLEAN      NOT NULL DEFAULT FALSE,
    -- 运行期标准输入（可选）
    stdin        VARCHAR(2000),
    -- 期望的标准输出（可选，用于自检提示）
    expected_out VARCHAR(2000),
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_snippet_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE
);
CREATE INDEX idx_snippet_lesson ON code_snippet (lesson_id, sort_order);

-- ---------- 课后习题（代码判题） ----------
CREATE TABLE code_exercise (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id    BIGINT,
    slug         VARCHAR(80)  NOT NULL,
    title        VARCHAR(160) NOT NULL,
    description  CLOB,
    difficulty   VARCHAR(20)  NOT NULL DEFAULT 'BEGINNER',
    language     VARCHAR(32)  NOT NULL DEFAULT 'java',
    -- 初始代码（学生在此基础上改）
    starter_code CLOB         NOT NULL,
    -- 参考答案（教师视角，不下发给学生）
    solution_code CLOB,
    -- 测试用例 JSON 数组：[{"name":"...","stdin":"...","expected":"..."}]
    test_cases   CLOB,
    hint         CLOB,
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_exercise_slug UNIQUE (slug)
);
CREATE INDEX idx_exercise_lesson ON code_exercise (lesson_id, sort_order);

-- ---------- 学生提交记录 ----------
CREATE TABLE code_submission (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT,
    exercise_id  BIGINT,
    source_code  CLOB         NOT NULL,
    -- COMPILE_ERROR / RUNTIME_ERROR / TIMEOUT / PASSED / FAILED
    status       VARCHAR(20)  NOT NULL,
    -- 判题明细 JSON：[{"name":"...","passed":true,"expected":"...","actual":"..."}]
    case_results CLOB,
    stdout       CLOB,
    stderr       CLOB,
    error_output CLOB,
    passed_count INTEGER      NOT NULL DEFAULT 0,
    total_count  INTEGER      NOT NULL DEFAULT 0,
    duration_ms  INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sub_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_sub_exercise FOREIGN KEY (exercise_id) REFERENCES code_exercise (id) ON DELETE CASCADE
);
CREATE INDEX idx_sub_user ON code_submission (user_id, created_at);
CREATE INDEX idx_sub_exercise ON code_submission (exercise_id, created_at);

CREATE TABLE knowledge_point (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(80)  NOT NULL,
    category     VARCHAR(40),
    description  VARCHAR(512),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_kp_name ON knowledge_point (name);

CREATE TABLE lesson_knowledge (
    lesson_id    BIGINT NOT NULL,
    kp_id        BIGINT NOT NULL,
    PRIMARY KEY (lesson_id, kp_id),
    CONSTRAINT fk_lk_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE,
    CONSTRAINT fk_lk_kp FOREIGN KEY (kp_id) REFERENCES knowledge_point (id) ON DELETE CASCADE
);
CREATE INDEX idx_lk_kp ON lesson_knowledge (kp_id);

CREATE TABLE qa_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id    BIGINT,
    owner_id     BIGINT,
    question     VARCHAR(512) NOT NULL,
    answer_text  CLOB,
    options_json VARCHAR(2000),
    answer_key   VARCHAR(32),
    qa_type      VARCHAR(20) NOT NULL DEFAULT 'SINGLE_CHOICE',
    difficulty   VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_qa_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE,
    CONSTRAINT fk_qa_owner FOREIGN KEY (owner_id) REFERENCES app_user (id) ON DELETE CASCADE
);
CREATE INDEX idx_qa_lesson ON qa_item (lesson_id);
CREATE INDEX idx_qa_owner ON qa_item (owner_id, id);

CREATE TABLE resource_file (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id    BIGINT,
    file_name    VARCHAR(255) NOT NULL,
    file_path    VARCHAR(512) NOT NULL,
    file_type    VARCHAR(64),
    file_size    BIGINT       NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_res_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE
);
CREATE INDEX idx_res_lesson ON resource_file (lesson_id);

-- ---------- 搜索索引（应用层分词，不依赖 tsvector） ----------
CREATE TABLE search_index (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type  VARCHAR(20)  NOT NULL,
    target_id    BIGINT       NOT NULL,
    title        VARCHAR(200) NOT NULL,
    body_text    CLOB,
    tokens       VARCHAR(4000),
    ref_url      VARCHAR(255),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_search_target ON search_index (target_type, target_id);
CREATE INDEX idx_search_title ON search_index (title);

-- ---------- 学习进度与收藏 ----------
CREATE TABLE learning_progress (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    lesson_id    BIGINT       NOT NULL,
    progress_pct INTEGER      NOT NULL DEFAULT 0,
    completed    SMALLINT     NOT NULL DEFAULT 0,
    -- 本次会话已学秒数（覆盖写）
    last_seconds INTEGER      NOT NULL DEFAULT 0,
    -- 累计有效学习秒数（累加写，统计总时长用）
    total_seconds INTEGER     NOT NULL DEFAULT 0,
    -- 学习次数：同一会话只计一次
    study_count  INTEGER      NOT NULL DEFAULT 0,
    -- 最近一次上报的会话标识，用于去重
    last_session_key VARCHAR(64),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lp_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_lp_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uk_lp_user_lesson ON learning_progress (user_id, lesson_id);

CREATE TABLE user_favorite (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    lesson_id    BIGINT       NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_uf_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_uf_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uk_uf_user_lesson ON user_favorite (user_id, lesson_id);

-- ---------- AI 助教 ----------
CREATE TABLE ai_chat_session (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT,
    title        VARCHAR(160),
    agent_key    VARCHAR(40) NOT NULL DEFAULT 'whale',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_acs_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);
CREATE INDEX idx_acs_user ON ai_chat_session (user_id, created_at);

CREATE TABLE ai_chat_message (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT       NOT NULL,
    role         VARCHAR(20)  NOT NULL,
    content      CLOB         NOT NULL,
    citations    VARCHAR(2000),
    token_usage  INTEGER      NOT NULL DEFAULT 0,
    latency_ms   INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_acm_session FOREIGN KEY (session_id) REFERENCES ai_chat_session (id) ON DELETE CASCADE
);
CREATE INDEX idx_acm_session ON ai_chat_message (session_id, created_at);

-- ---------- 生成审计（AI 建站流水线留痕） ----------
CREATE TABLE generation_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      VARCHAR(64),
    source_type  VARCHAR(32),
    source_path  VARCHAR(512),
    model_name   VARCHAR(80),
    prompt_hash  VARCHAR(64),
    target_type  VARCHAR(32),
    target_id    BIGINT,
    result_status VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
    detail       CLOB,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_genlog_task ON generation_log (task_id);
CREATE INDEX idx_genlog_created ON generation_log (created_at);

-- ---------- 用户私有课程草稿与只读分享 ----------
CREATE TABLE generated_course (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT NOT NULL,
    title         VARCHAR(160) NOT NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    source_name   VARCHAR(255),
    source_url    VARCHAR(1000),
    source_text   CLOB,
    course_json   CLOB NOT NULL,
    share_token   VARCHAR(64),
    share_revoked SMALLINT NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_generated_owner FOREIGN KEY (owner_id) REFERENCES app_user (id) ON DELETE CASCADE
);
CREATE INDEX idx_generated_owner ON generated_course (owner_id, updated_at);
CREATE UNIQUE INDEX uk_generated_share ON generated_course (share_token);

-- 每日真实学习累积；同一会话的重复心跳以 session_seconds 做增量去重。
CREATE TABLE learning_activity (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    lesson_id       BIGINT NOT NULL,
    session_key     VARCHAR(64) NOT NULL,
    activity_date   DATE NOT NULL DEFAULT CURRENT_DATE,
    session_seconds INTEGER NOT NULL DEFAULT 0,
    total_seconds   INTEGER NOT NULL DEFAULT 0,
    completed       SMALLINT NOT NULL DEFAULT 0,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_activity_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_activity_lesson FOREIGN KEY (lesson_id) REFERENCES lesson (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uk_activity_session_day ON learning_activity (user_id, lesson_id, session_key, activity_date);
CREATE INDEX idx_activity_user_day ON learning_activity (user_id, activity_date);

CREATE TABLE learning_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    lesson_id BIGINT NOT NULL,
    session_key VARCHAR(64) NOT NULL,
    last_seconds INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_learning_session_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_learning_session_lesson FOREIGN KEY (lesson_id) REFERENCES lesson(id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uk_learning_session_key ON learning_session(user_id,lesson_id,session_key);

-- Per-account AI provider settings; API keys are AES-GCM encrypted by the backend.
CREATE TABLE user_ai_config (
    user_id BIGINT PRIMARY KEY,
    base_url VARCHAR(1000) NOT NULL,
    model VARCHAR(160) NOT NULL,
    encrypted_key VARCHAR(4096) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_ai_config_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE
);
